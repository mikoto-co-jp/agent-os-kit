#!/bin/sh
# PII pre-commit 関門（2026-08-09 設置・経理レーン実害2件が起点）
# ステージされた差分に 口座番号/カード番号/マイナンバー らしきパターンが入ったら commit を止める
#
# UUID（8-4-4-4-12）は先に <UUID> へ潰す。UUID の真ん中の 4-4-4-4 が
# カード番号の式に当たるため（出所: 2026-09-19 にプロンプト資産 234 枚を git に載せたとき
# id: "<8桁-4桁-4桁-4桁-12桁 の形の識別子>" の 2 行が偽陽性で止めた）。
#     ⛔ ここに実物の識別子を書かない——配布物の門（check-distributable.sh）が固有値として弾き、
#        make-kit.sh --selftest が落ちて器キットが切り出せなくなる（2026-09-19 に実際に起きた）。
# ⚠️ 潰すのは 36 字そろった UUID だけ。本物のカード番号（4-4-4-4）は 8 字の頭を持たないので残る。
d=$(git diff --cached --unified=0 -- '*.md' '*.csv' '*.json' 2>/dev/null | grep '^+' | grep -v '^+++' \
    | sed -E 's/[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}/<UUID>/g')
echo "$d" | grep -nE '(普通|当座)[ 　]*[0-9]{7}|[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{4}|マイナンバー.*[0-9]{12}' >/dev/null 2>&1 && {
  echo "🚨 PII らしき文字列（口座番号/カード番号/個人番号）が commit に含まれています。経理/docs/作業/（ignore済）へ移すか、--no-verify で明示的に上書きしてください" >&2
  exit 1
}
exit 0
